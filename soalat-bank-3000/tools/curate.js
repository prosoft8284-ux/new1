/* ---------- تجزیه ---------- */
function parse(raw) {
  const lines = raw.replace(/\r/g, '').split('\n');
  const head = [];
  const sections = [];
  let cur = null;
  let item = null;
  for (const line of lines) {
    const t = line.trim();
    const sec = t.match(/^—\s*(.+?)\s*—$/);
    const isSep = /^—{5,}$/.test(t);
    if (sec && !isSep) {
      cur = { title: sec[1], lines: [], items: [] };
      sections.push(cur);
      item = null;
      continue;
    }
    if (!cur) { head.push(line); continue; }
    const qm = t.match(/^([۰-۹]+)\)/);
    if (qm) {
      item = { num: +toEn(qm[1]), lines: [line] };
      cur.items.push(item);
      continue;
    }
    if (item && t) item.lines.push(line);
    else if (item && !t) item.lines.push(line);
    else cur.lines.push(line);
  }
  return { head, sections };
}

function block(stem, options, key, exp) {
  return { stem, options, key, exp };
}

function renderItem(n, it) {
  return [
    `${fa(n)}) ${it.stem}`,
    ...it.options.map((o, i) => `   ${fa(i + 1)}. ${o}`),
    `   ✔ کلید: گزینه ${fa(it.key)}`,
    `   ✎ تحلیل: ${it.exp}`,
    '',
  ];
}

const dry = process.argv.includes('--dry');
let failed = false;

for (const [file, spec] of Object.entries(SPEC)) {
  const full = path.join(DIR, file);
  const raw = fs.readFileSync(full, 'utf8');
  const { head, sections } = parse(raw);
  const before = sections.reduce((a, s) => a + s.items.length, 0);

  // ۱) برداشتن تکرارها
  const drops = new Set(spec.drop);
  const found = new Set();
  for (const s of sections) {
    s.items = s.items.filter((it) => {
      if (!drops.has(it.num)) return true;
      found.add(it.num);
      return false;
    });
  }
  for (const d of drops) if (!found.has(d)) {
    console.error(`✗ ${file}: سوال ${fa(d)} برای حذف پیدا نشد`);
    failed = true;
  }

  // ۲) درج سوال‌های تازه
  const added = [];
  for (const ins of spec.insert) {
    const items = ins.items.map((x) => block(x.stem, x.options, x.key, x.exp));
    if (ins.title) {
      const idx = sections.findIndex((s) => s.title.includes(ins.after));
      if (idx < 0) { console.error(`✗ ${file}: بخش «${ins.after}» پیدا نشد`); failed = true; continue; }
      sections.splice(idx + 1, 0, { title: ins.title, lines: [''], items });
    } else {
      const sec = sections.find((s) => s.title.includes(ins.into));
      if (!sec) { console.error(`✗ ${file}: بخش «${ins.into}» پیدا نشد`); failed = true; continue; }
      sec.items.push(...items);
    }
    added.push(...items);
  }

  // ۳) بازشماری سوال‌ها
  let n = 0;
  for (const s of sections) {
    for (const it of s.items) {
      n += 1;
      if (it.lines) {
        const rest = it.lines[0].replace(/^\s*[۰-۹]+\)\s*/, '');
        it.lines[0] = `${fa(n)}) ${rest.trim()}`;
      }
      it.num = n;
    }
  }

  // ۴) بازشماری بخش‌های شماره‌دار
  let sn = 0;
  for (const s of sections) {
    const m = s.title.match(/^بخش\s*[۰-۹]+\s*:\s*(.+)$/);
    if (m) {
      sn += 1;
      s.title = `بخش ${fa(sn)}: ${m[1].trim()}`;
    }
  }

  // ۵) به‌روزرسانی ارجاع شماره سوال در متن‌های درک مطلب
  for (const s of sections) {
    if (!s.items.length) continue;
    s.lines = s.lines.map((l) =>
      l.replace(/به پرسش‌های\s*[۰-۹]+\s*تا\s*[۰-۹]+/, `به پرسش‌های ${fa(s.items[0].num)} تا ${fa(s.items[s.items.length - 1].num)}`)
    );
  }

  // ۶) خروجی
  const out = [];
  for (const l of head) {
    if (/^تعداد سوال این فایل:/.test(l.trim())) {
      out.push(`تعداد سوال این فایل: ${fa(n)} | هر سوال ۴ گزینه دارد؛ کلید و تحلیل زیر همان سوال آمده است.`);
    } else out.push(l);
  }
  for (const s of sections) {
    out.push(`— ${s.title} —`);
    for (const l of s.lines) out.push(l);
    for (const it of s.items) {
      // آیتم‌های قدیمی خطوط خود را دارند؛ آیتم‌های تازه از روی block ساخته می‌شوند
      if (it.lines) out.push(...it.lines);
      else out.push(...renderItem(it.num, it));
    }
  }

  console.log(`${file}: ${before} → ${n} (حذف ${spec.drop.length}، افزودن ${added.length})`);
  if (before - spec.drop.length + added.length !== n) {
    console.error('✗ شمارش با انتظار نمی‌خواند');
    failed = true;
  }
  if (!dry) fs.writeFileSync(full, out.join('\n').replace(/\n{4,}/g, '\n\n\n'));
}

process.exitCode = failed ? 1 : 0;
