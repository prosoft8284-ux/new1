let bad = 0;
let count = 0;
for (const [file, pairs] of Object.entries(FIXES)) {
  const full = path.join(DIR, file);
  let txt = fs.readFileSync(full, 'utf8');
  for (const [oldExp, newExp] of pairs) {
    const needle = `✎ تحلیل: ${oldExp}`;
    const parts = txt.split(needle);
    if (parts.length !== 2) {
      console.error(`✗ ${file}: «${oldExp.slice(0, 40)}…» ${parts.length - 1} بار پیدا شد`);
      bad++;
      continue;
    }
    txt = parts[0] + `✎ تحلیل: ${newExp}` + parts[1];
    count++;
  }
  fs.writeFileSync(full, txt);
}
console.log(`تحلیل‌های بازنویسی‌شده: ${count}` + (bad ? ` | خطا: ${bad}` : ''));
process.exitCode = bad ? 1 : 0;
